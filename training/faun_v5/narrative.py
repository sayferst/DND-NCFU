def atmosphere(kind, p, b, r, scene):
    """All physical claims are limited to the computed event; speech expresses opinions."""
    n, s = r["numbers"], r["state_after"]
    if kind == "overcast":
        return (
            "Цену нужно оценить до применения."
            if not n["attempt_possible"]
            else ("Магическое усилие оплачено указанным способом.")
        )
    if kind == "social":
        return "Собеседник готов к соглашению." if n["agreed"] else "Разговор ещё требует решения."
    if kind in ("craft", "repair"):
        return {
            "success": "Соединение держится; работа доведена до заявленной пригодности.",
            "partial": (
                "Получилась лишь заготовка. До полноценного использования её придётся доработать."
            ),
            "failure": (
                "Задуманного качества достичь не удалось; попытка уже стоила материалов и сил."
            ),
            "blocked": "Работу стоит начать с проверки инструмента и запаса материала.",
        }[n["outcome"]]
    if kind == "heal":
        return (
            "Раненый приходит в себя."
            if not b["conscious"] and s["conscious"]
            else (
                "Восстановление достигло предела здоровья."
                if s["hp"] == s["hp_max"]
                else "После лечения часть ран ещё остаётся."
            )
        )
    if kind in ("bonus_action", "reaction"):
        return (
            "Обсуждение ещё продолжается."
            if p.get("intent_only")
            else (
                "Этот ресурс хода израсходован."
                if n["available"]
                else "Повторить действие за тот же ресурс сейчас нельзя."
            )
        )
    if kind == "concentration":
        return (
            "Внимание удерживает только одно заклинание."
            if s["concentration"]
            else ("Прежний эффект концентрации прекращается.")
        )
    if kind == "death_save":
        return (
            "Борьба за жизнь закончилась смертью."
            if s["dead"]
            else (
                "Герой вновь в сознании."
                if s["conscious"]
                else "Герой остаётся без сознания; окружающим важно знать его точное состояние."
            )
        )
    if kind == "nonlethal":
        return "Цель лежит без сознания и стабильна." if s["hp"] == 0 else "Цель выдержала удар."
    if kind == "door":
        return "Замок больше не удерживает дверь." if r["success"] else "Замок не поддался."
    if kind == "trap":
        return (
            "Указанного воздействия удалось избежать." if r["success"] else "Ловушка задела героя."
        )
    if kind == "charges":
        return (
            "Предмет исчерпал запас зарядов." if s["charges"] == 0 else "Часть зарядов сохранена."
        )
    if kind == "duration":
        return (
            "Время эффекта ещё не вышло."
            if s["effect_active"]
            else "Эффект угасает по истечении срока."
        )
    if kind == "rest":
        return "После завершённого отдыха можно заново оценить силы."
    if kind == "inventory":
        return (
            "Передача состоялась."
            if r["success"] and r["committed"]
            else ("Просьба о передаче не изменила фактического держателя.")
        )
    if kind == "quest":
        return (
            "Условие возврата выполнено."
            if s["condition_met"]
            else "Возврат ещё предстоит подтвердить."
        )
    if kind == "reward":
        return (
            "Расчёт завершён."
            if n["paid"] and r["committed"]
            else ("Расчёт пока остаётся открытым вопросом.")
        )
    if kind == "unknown":
        return (
            "Сказанное можно подтвердить."
            if n["established"]
            else "В разговоре есть пробел, который стоит уточнить."
        )
    if kind == "catalog_lookup":
        return "Указатель помогает найти запись, но полное описание здесь отсутствует."
    if kind == "ability":
        return (
            "Нужное свойство подтверждено."
            if n["goal_reachable"]
            else ("Для самой цели требуется свойство, которого сейчас нет.")
        )
    if kind in ("spell_slot", "cantrip"):
        return (
            "Способ доступен."
            if n["can_cast"]
            else "Для этого способа сейчас не выполнены условия."
        )
    if kind == "movement":
        return (
            "Запаса хватит на весь переход."
            if n["can_reach"]
            else "Весь путь за этот ход не пройти."
        )
    if kind == "damage":
        return "Цель теряет сознание." if s["hp"] == 0 else "Цель остаётся в сознании."
    if kind == "damage_zero":
        return (
            "Цель погибает от нового урона."
            if s["dead"]
            else "Новый урон прерывает стабильное состояние."
        )
    if kind == "stabilize":
        return (
            "Непосредственная опасность миновала."
            if n["stabilized"]
            else "Борьба за жизнь продолжается."
        )
    if kind == "ranged":
        return (
            "Можно готовить выстрел."
            if n["can_attack"]
            else "Нужно изменить дистанцию или выбрать другой способ."
        )
    return "Проверка удалась." if r["success"] else "Проверка не удалась."


# Different compositions, rather than a split prefix attached to identical templates.
COMPOSITIONS = {
    "train": ("fact_then_reply", "reply_then_fact", "result_then_choice"),
    "val": ("question_and_account", "account_and_question"),
    "test": ("witness_and_response", "response_and_witness"),
    "ood": ("disputed_assumption", "changed_context"),
}


def render(kind, p, before, result, scene, mode, rng, fold):
    core = summary(kind, p, before, result)
    composition = rng.choice(COMPOSITIONS[fold])
    if mode == "A":
        # Compact calculation remains compact. Different syntax is held out, not the rule.
        if fold == "val":
            core = "Итог проверки условий: " + core
        elif fold == "test":
            core = "По указанным числам получается следующее. " + core
        elif fold == "ood":
            core = "В этой комбинации условий: " + core
        return core, {"mode": mode, "narrative_family": composition + ":compact"}
    a, b = scene["npc"], scene["other_npc"]
    event = atmosphere(kind, p, before, result, scene)
    voices = {
        "осторожный": (
            "Сначала оценим то, что осталось в нашем распоряжении.",
            "Мне важно понимать, чем мы рискуем дальше.",
        ),
        "прямой": (
            "Назови следующий шаг, когда решишь.",
            "Я за ясный разговор: что именно ты предлагаешь?",
        ),
        "педантичный": (
            "Я буду опираться на этот итог при следующей проверке.",
            "Давай сохраним порядок, иначе запутаемся в собственных решениях.",
        ),
        "сочувствующий": (
            "Главное — понять, кому сейчас нужна помощь.",
            "Я хочу, чтобы следующий шаг помог людям, а не только закрыл спор.",
        ),
        "недоверчивый": (
            "Вот с этими фактами я готов обсуждать предложение.",
            "Сначала уточни, на чём будет основано твоё решение.",
        ),
        "практичный": (
            "Теперь видно, какими средствами можно распорядиться.",
            "Предложи то, что можно сделать с оставшимся запасом.",
        ),
    }
    line = rng.choice(voices[scene["temperament"]]).rstrip(".")
    # Tone follows the event; NPC reactions are speech, not invented resources.
    situational = {
        "death_save": [
            "Мы должны учитывать именно это состояние",
            "Сейчас важен исход борьбы за жизнь",
        ],
        "damage_zero": ["Теперь счёт идёт на помощь товарищу", "Нужно знать, можно ли ещё помочь"],
        "stabilize": [
            "Сначала разберёмся, какая помощь ещё нужна",
            "Важно не путать стабильность с выздоровлением",
        ],
        "heal": [
            "Оценим, какая помощь ещё нужна раненому",
            "Теперь понятнее, сколько сил осталось у раненого",
        ],
        "nonlethal": [
            "Мы договаривались о нелетальном ударе",
            "Важно знать, в каком состоянии цель",
        ],
        "charges": [
            "Как ты предлагаешь распорядиться оставшимся запасом",
            "Запас стоит учитывать перед следующим применением",
        ],
        "duration": ["Время нужно учитывать в следующем решении", "Как это меняет твой план"],
        "craft": [
            "Оценим пригодность работы для нашей цели",
            "Что ты предложишь сделать с этим результатом",
        ],
        "repair": [
            "Сверим результат с тем, ради чего затевали ремонт",
            "Что теперь нужно для завершения работы",
        ],
        "inventory": [
            f"Сейчас вещь хранится у держателя: {result['state_after']['holder']}",
            "К кому ты хочешь обратиться дальше",
        ],
        "unknown": [
            "Давай уточним именно это событие",
            "Я хочу отделить свидетельство от предположения",
        ],
        "quest": [
            "Предлагаю вернуться к условию возврата",
            "Что осталось уточнить в договорённости",
        ],
        "reward": ["Давай обсудим фактический расчёт", "Как ты хочешь продолжить этот разговор"],
        "door": [
            "Теперь решим, что делать с самой дверью",
            "Замок и дверь требуют разных действий",
        ],
        "trap": [
            "После этого стоит оценить дальнейший путь",
            "Как ты предлагаешь двигаться дальше",
        ],
    }
    if kind in situational:
        line = rng.choice(situational[kind])
    if composition == "fact_then_reply":
        paragraphs = [core, f"— {line}, — говорит {a}."]
    elif composition == "reply_then_fact":
        paragraphs = [f"— {line}, — {a} обращается к герою.", core]
    elif composition == "result_then_choice":
        paragraphs = [core, f"{a} ждёт твоего решения: «{line}»."]
    elif composition == "question_and_account":
        paragraphs = [f"{a} уточняет: «Что у нас в итоге?»", core, event + " «" + line + "»."]
