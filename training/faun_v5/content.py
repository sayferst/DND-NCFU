def summary(kind, p, b, r):
    n = r["numbers"]
    s = r["state_after"]
    intent = not r["committed"]
    if kind == "overcast":
        if not n["attempt_possible"]:
            return "Перерасход сейчас недоступен по указанным ограничениям; ресурсы сохранены."
        return (
            f"Нехватка: {n['missing']} MP. Потрачено здоровья: {n['hp_cost']}; "
            f"истощения добавлено: {n['exhaustion_cost']}. "
            f"Теперь MP {s['mp']}, HP {s['hp']}, истощение {s['exhaustion']}. "
            + (
                "Шестой уровень истощения смертелен."
                if s["dead"]
                else "Герой без сознания при 0 HP."
                if not s["conscious"]
                else "Герой остаётся в сознании."
            )
            + (
                " Заклинание удалось."
                if n["outcome"] == "success"
                else " Заклинание не удалось, но цена уже оплачена."
            )
        )
    if kind == "social":
        if n["clarification_required"]:
            return (
                "Нужно уточнить полномочия или жизненно важные ограничения NPC, "
                "прежде чем решать исход просьбы."
            )
        if n["agreed"]:
            return (
                f"Убеждение {n['total']} против сложности {p['threshold']}: "
                f"NPC соглашается на выполнимую просьбу в пределах своих "
                f"полномочий."
            )
        return (
            f"Убеждение {n['total']} при сложности {p['threshold']}. "
            "Согласие не получено: проверка или обязательные условия просьбы не выполнены."
        )
    if kind == "attack":
        return f"{p['roll']} + {p['modifier']} = {n['total']}; КБ {p['threshold']}. " + (
            f"Попадание: урон {n['damage']}, у противника остаётся {n['hp_after']} HP."
            if n["success"]
            else f"Промах. У противника по-прежнему {s['hp']} HP."
        )
    if kind in ("save", "skill", "door", "trap"):
        line = f"{p['roll']} + {p['modifier']} = {n['total']} при сложности {p['threshold']}: " + (
            "успех." if n["success"] else "провал."
        )
        if kind == "door":
            line += " " + (
                "Замок отперт, но дверь ещё не открыта."
                if n["success"]
                else "Замок остаётся заперт."
            )
        if kind == "trap" and not n["success"]:
            line += f" Ловушка наносит {p['damage']} урона; остаётся {s['hp']} HP."
        return line
    if kind in ("advantage", "disadvantage"):
        return (
            f"Из {p['dice'][0]} и {p['dice'][1]} выбирается "
            f"{n['chosen_die']}. {n['chosen_die']} + {p['modifier']} = "
            f"{n['total']} против сложности {p['threshold']}: "
        ) + ("успех." if n["success"] else "провал.")
    if kind == "damage":
        reason = (
            "Иммунитет обнуляет урон"
            if p["immune"]
            else "Сопротивление применяется один раз с округлением вниз"
            if p["resistant"]
            else "Уязвимость удваивает урон"
            if p["vulnerable"]
            else "Снижения урона нет"
        )
        return (
            f"{reason}: из {p['raw']} получается {n['damage']} урона. "
            f"Было {b['hp']} HP, остаётся {s['hp']} HP."
        )
    if kind == "heal":
        return (
            f"Восстановлено {n['healed']} HP: теперь {s['hp']} из "
            f"{s['hp_max']}. Лечение ограничено максимумом здоровья."
        )
    if kind == "movement":
        base = f"Доступно {n['remaining_before']} футов движения; требуется {n['required']}. "
        if intent:
            return (
                base
                + (
                    "Движения хватит."
                    if n["can_reach"]
                    else f"Весь участок не пройти; доступно {n['max_path']} футов пути."
                )
                + " Это оценка возможности: переход ещё не начат."
            )
        return base + (
            f"Переход выполнен; израсходовано {s['movement_spent']} футов движения за ход."
            if n["can_reach"]
            else "Переход целиком не выполнен; положение и запас движения сохранены."
        )
    if kind in ("spell_slot", "cantrip"):
        if not n["can_cast"]:
            return (
                "Обычным способом применить эффект сейчас нельзя: не "
                "подтверждены нужное знание или подходящая ячейка. Ресурс "
                "сохранён."
            )
        if intent:
            return (
                "Применение доступно. Пока обсуждается возможность, ячейка не "
                "тратится и эффект не возникает."
            )
        return (
            "Известный заговор применён без расхода ячейки."
            if kind == "cantrip"
            else f"Заклинание применено; ячеек выбранного уровня осталось {s['slots']}."
        )
    if kind == "concentration":
        return (
            (
                f"Сложность max(10, {p['damage']} // 2) = {n['dc']}; итог "
                f"спасброска {p['save_total']}: "
            )
            + ("успех. " if n["save_success"] else "провал. ")
            + (
                "Концентрация прекращена."
                if s["concentration"] is None
                else f"Сейчас поддерживается только {s['concentration']}."
            )
        )
    if kind == "death_save":
        if p["roll"] == 20:
            return (
                "Натуральная 20 восстанавливает 1 HP; персонаж приходит в "
                "сознание, счётчики спасбросков обнулены."
            )
        prefix = (
            f"В этой серии накоплено успехов: "
            f"{n['successes_accumulated']}; провалов: "
            f"{n['failures_accumulated']}. "
        )
        return prefix + (
            "Персонаж погиб: провалов не меньше трёх."
            if s["dead"]
            else "Персонаж стабилен при 0 HP и без сознания; счётчики обнулены."
            if s["stable"]
            else "Персонаж остаётся без сознания при 0 HP и ещё не стабилизирован."
        )
    if kind == "nonlethal":
        return f"После нелетального удара остаётся {s['hp']} HP. " + (
            "Цель без сознания и сразу стабильна по правилу проекта."
            if s["hp"] == 0
            else "Цель остаётся в сознании."
        )
    if kind == "damage_zero":
        return f"Добавлено провалов: {n['added_failures']}; теперь {n['failures']}. " + (
            "Цель погибла." if n["dead"] else "Цель без сознания, не стабильна, HP по-прежнему 0."
        )
    if kind == "stabilize":
        return f"Медицина: {n['total']} против сложности {p['threshold']}. " + (
            "Цель стабильна при 0 HP, без сознания; счётчики обнулены."
            if n["stabilized"]
            else "Стабилизировать цель не удалось; состояние прежнее."
        )
    if kind == "ranged":
        return (
            "Цель вне максимальной дальности: такая атака недоступна."
            if not n["can_attack"]
            else "Дальность допускает атаку с помехой."
            if n["disadvantage"]
            else "Цель в нормальной дальности; помехи из-за расстояния нет."
        )
    if kind in ("bonus_action", "reaction"):
        name = "Бонусное действие" if kind == "bonus_action" else "Реакция"
        return name + (
            " доступна; сейчас обсуждается её применение."
            if intent and n["available"]
            else " недоступна: ресурс уже потрачен."
            if not n["available"]
            else " использована; до восстановления ресурса повторить её нельзя."
        )
    if kind == "inventory":
        return (
            f"Предмет «{p['item_name']}» находится у получателя: {s['holder']}."
            if r["success"] and not intent
            else (
                f"Предмет «{p['item_name']}» по-прежнему находится у держателя: "
                f"{s['holder']}. Подтверждённой передачи нет."
            )
        )
    if kind == "charges":
        return (
            f"Срабатываний: {n['activations']}. Заряды: {b['charges']} − "
            f"{n['activations']} = {s['charges']}."
        )
    if kind == "rest":
        return (
            f"Подтверждённый длительный отдых завершён: HP "
            f"{s['hp']}/{s['hp_max']}, ячеек {s['slots']}, истощение "
            f"{s['exhaustion']}."
        )
    if kind == "duration":
        return f"Осталось {s['duration']} мин. " + (
            "Эффект ещё действует." if s["effect_active"] else "Срок истёк, эффект прекратился."
        )
    if kind == "quest":
        return (
            "Возврат принят: условие задания выполнено. Награда пока не передана."
            if s["condition_met"]
            else "Условие задания ещё не выполнено; обещание награды остаётся обещанием."
        )
    if kind == "reward":
        if intent:
            return "Возможность выплаты проверена, но фактической передачи денег ещё не было."
        return (
            f"Награда {p['amount']} монет передана; у героя теперь {s['coins']}."
            if n["paid"]
            else (
                "Выплата не состоялась: не выполнено условие задания или "
                "недостаточно средств у плательщика."
            )
        )
    if kind == "catalog_lookup":
        return (
            f"В указателе есть запись «{p['name']}», категория "
            f"«{p['category']}». Другие характеристики в доступной "
            f"записи не приведены."
        )
    if kind == "unknown":
        return (
            "Предоставленные сведения подтверждают запрошенный факт."
            if n["established"]
            else (
                "Предоставленные сведения этого не подтверждают. Сначала нужно "
                "уточнить, происходило ли предполагаемое событие."
            )
        )
    if kind in ("craft", "repair"):
        label = {
            "success": "Работа удалась: результат пригоден к заявленной цели.",
            "partial": "Получена незавершённая заготовка; качество ограничено.",
            "failure": "Работа не удалась.",
            "blocked": (
                "Для этой работы не хватает подтверждённых материалов, "
                "инструмента или доступного способа."
            ),
        }[n["outcome"]]
        if n["outcome"] != "blocked":
            label += f" Материалов осталось {s['materials']}; ST: {b['stamina']} → {s['stamina']}."
        return label
    if kind == "ability":
        return (
            (
                "Проверяемое свойство у предмета зарегистрировано; способ "
                "применения нужно согласовать с его ограничениями."
            )
            if n["goal_reachable"]
            else (
                "Попытаться физически можно, но у предмета нет нужного "
                "свойства. Бросок D20 не создаст его."
            )
        )
    raise ValueError(kind)
