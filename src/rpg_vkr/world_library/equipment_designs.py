"""Original visual designs around source facts; never source construction claims."""

import hashlib


def enrich(record):
    a = record["attributes"]
    name, section = a["source_name"].casefold(), a["section"]
    parts = []
    if section == "Товары и ценности":
        purpose = "Справочная мера товара для сопоставления цен и составления торговых предложений."
        appearance = (
            "Торговая запись; внешний вид конкретной партии задаётся при её появлении в мире."
        )
    elif section == "Оружие" and "лук" in name and "арбалет" not in name:
        purpose = "Дистанционное оружие для одиночных прицельных выстрелов подходящими стрелами."
        appearance = "Тисовые плечи с плавным изгибом; пеньковая тетива и кожаная обмотка хвата."
        parts = [(1, "плечи"), (5, "тетива"), (6, "обмотка хвата")]
    elif section == "Оружие" and any(w in name for w in ("арбалет", "чо-ко-ну")):
        purpose = (
            "Дистанционное оружие с механическим удержанием тетивы и направляющей для боеприпаса."
        )
        appearance = "Ясеневая ложа, стальные дуга и спусковой узел; натянутая пеньковая тетива."
        parts = [(0, "ложа"), (9, "дуга и спуск"), (5, "тетива")]
    elif section == "Оружие":
        material = (
            14
            if any(w in name for w in ("кост", "клык", "клыка"))
            else 15
            if "камен" in name
            else 9
        )
        if any(w in name for w in ("посох", "дубин", "палиц", "шест")):
            purpose = "Оружие ближнего боя с усиленной ударной частью и местом для надёжного хвата."
            appearance = "Цельная дубовая основа; на рукояти шероховатая кожаная обмотка."
            parts = [(2, "основа"), (6, "обмотка")]
        elif any(w in name for w in ("кнут", "лассо", "сеть", "бич", "бола")):
            purpose = (
                "Гибкое оружие; точный приём и допустимая цель определяются "
                "отдельным действием движка."
            )
            appearance = "Плетёная пеньковая основа, усиленные кожаные участки хвата и соединений."
            parts = [(5, "плетение"), (6, "усиление хвата")]
        else:
            purpose = (
                "Ручное оружие; рабочая часть направляет удар, "
                "а рукоять удерживает его под контролем."
            )
            material_name = {9: "Стальная", 14: "Костяная", 15: "Каменная"}[material]
            appearance = (
                f"{material_name} рабочая часть с ровным краем; ясеневая рукоять в кожаной обмотке."
            )
            parts = [(material, "рабочая часть"), (0, "рукоять"), (6, "обмотка")]
    elif section == "Доспехи":
        material = (
            6
            if any(w in name for w in ("кож", "шкур"))
            else 14
            if "кост" in name
            else 4
            if "стёган" in name
            else 9
        )
        purpose = (
            "Защитное снаряжение; защищает только при корректном надевании и сохранной прочности."
        )
        appearance = (
            "Защитные детали закреплены на льняной подкладке кожаными ремнями; "
            "края аккуратно подогнаны."
        )
        parts = [(material, "защитный слой"), (4, "подкладка"), (6, "крепления")]
        if "бронз" in name:
            parts[0] = (10, "бронзовый защитный слой")
        if "хитин" in name:
            appearance = (
                "Хитиновые пластины с матовой поверхностью; льняная подкладка и кожаные ремни."
            )
            parts = [(4, "подкладка"), (6, "крепления")]
    elif section in {"Яды", "Наркотики и вещества", "Взрывчатка"}:
        purpose = (
            "Особое игровое расходное средство; эффект требует отдельной "
            "проверенной механики применения."
        )
        appearance = (
            "Закрытая маркированная тара с плотной обмоткой; "
            "состав содержимого визуально не определяется."
        )
        parts = [(13, "тара"), (4, "уплотнение и обмотка")]
    elif section == "Огнестрельное оружие":
        purpose = (
            "Стрелковое снаряжение своего технологического уровня; "
            "тип боеприпаса задаётся отдельно."
        )
        appearance = (
            "Металлический корпус с матовыми деталями; поверхность хвата сделана шероховатой."
        )
        parts = [(9, "корпус"), (6, "накладка хвата")]
        if any(word in name for word in ("патрон", "пули", "батарея")):
            purpose = (
                "Запас для совместимого стрелкового устройства; упаковка учитывается поштучно."
            )
            appearance = (
                "Небольшие маркированные элементы в закрытой таре; целостность проверяют снаружи."
            )
            parts = []
    elif section == "Осадное снаряжение":
        purpose = (
            "Крупное осадное устройство; его перемещение и использование требуют расчёта и места."
        )
        appearance = (
            "Массивная дубовая рама, стальные крепления и пеньковые тяги; "
            "опоры заметно шире корпуса."
        )
        parts = [(2, "рама"), (9, "крепления"), (5, "тяги")]
    elif section == "Инструменты" or any(w in name for w in ("инструмент", "набор", "комплект")):
        purpose = (
            "Рабочий комплект для соответствующего занятия; "
            "наличие комплекта не даёт владение навыком."
        )
        appearance = "Кожаная укладка с отдельными гнёздами; рабочие детали закреплены ремешками."
        parts = [(6, "укладка"), (9, "рабочие детали")]
    elif any(w in name for w in ("книг", "бумаг", "пергамент", "карта")):
        purpose = (
            "Материал для хранения и передачи записей; "
            "текст и авторство экземпляра задаются в мире."
        )
        appearance = (
            "Светлые листы с неровной кромкой; наружная сторона защищена мягкой кожаной обложкой."
        )
        parts = [(4, "волокнистые листы"), (6, "защита листов")]
    elif any(w in name for w in ("одежд", "одеял", "спальник", "палатк", "ряса")):
        purpose = (
            "Походная или повседневная тканевая вещь; фасон определяет способ ношения и укрытия."
        )
        appearance = (
            "Плотная льняная основа, шерстяная прослойка и кожаные завязки на нагруженных участках."
        )
        parts = [(4, "основа"), (7, "прослойка"), (6, "завязки")]
    else:
        purpose = (
            "Предмет повседневного или походного обихода; "
            "конкретное применение следует его назначению."
        )
        appearance = (
            "Рабочая поверхность без лишнего декора; края сглажены, "
            "соединения доступны для осмотра."
        )
        # Unknown fantasy mechanisms do not receive a fabricated full material recipe.
    stamp = ("три точки", "перекрещённые линии", "полумесяц", "маленький квадрат")[
        hashlib.sha256(record["id"].encode()).digest()[0] % 4
    ]
    if section != "Товары и ценности":
        appearance += f" На наружной стороне метка мастерской: {stamp}."
    history = (
        "У шаблона нет подтверждённого прежнего владельца; "
        "личная история закрепляется за экземпляром."
    )
    a.update(
        purpose_homebrew=purpose,
        appearance_homebrew=appearance,
        history_homebrew=history,
        design_origin="invented/homebrew",
    )
    # Duplicate material layers are combined into a single canonical material dependency.
    record["links"] = [
        {
            "target": f"wl_material_{material}",
            "relation": "component",
            "quantity": 1,
            "role": "; ".join(role for number, role in parts if number == material),
        }
        for material in dict.fromkeys(number for number, _ in parts)
    ]
    record["description"] = f"{a['source_name']}. {purpose} {appearance} {history}"
