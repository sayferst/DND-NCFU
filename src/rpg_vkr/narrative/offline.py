"""A small authored scene; no language model, SRD mechanics or persistent state."""

from rpg_vkr.commands import normalise_action

INTRODUCTION = (
    "Вы подходите к воротам небольшой деревни. Стражник наблюдает за дорогой, "
    "а рядом жительница собирает яблоки из опрокинувшейся корзины. "
    "Впереди виднеются площадь и вывеска таверны. Что вы сделаете?"
)

HELP = (
    "Эпизод «Доставка на рынок»: взять поручение → идти на дорогу → исследовать дорогу → "
    "идти на рынок → доставить корзину. Лавка: торговля, купить бинт, продать бинт. "
    "Лечение: использовать бинт. Информация: состояние, инвентарь, задание. "
    "Назад: идти к воротам. "
    "Пока доступны действия: «осмотреться», «поговорить», «помочь» и «бросить d20». "
    "Для учебной проверки напишите «проверить силу» или «проверить мудрость» "
    "(также доступны остальные характеристики); сложность — 10, без владения навыками. "
    "Можно также написать «поговорить со стражником» или «помочь собрать яблоки». "
    "Команда «помощь» снова покажет эту подсказку."
)

OBSERVE = (
    "У ворот тихо. На дороге остались следы телеги, на площади слышны голоса. "
    "Стражник готов поговорить, а жительнице нужна помощь с рассыпавшимися яблоками."
)

TALK = (
    "Стражник кивает: «Добро пожаловать. Таверна прямо за площадью. "
    "Если есть минутка, помогите нашей соседке с корзиной»."
)

HELP_NEIGHBOUR = (
    "Вы помогаете собрать рассыпавшиеся яблоки. Жительница благодарит вас: "
    "«Спасибо, путник! Теперь я успею на рынок». Это небольшое доброе дело "
    "становится первым событием вашего путешествия."
)

_REPLIES = {
    "осмотреться": OBSERVE,
    "осмотреть деревню": OBSERVE,
    "я осматриваюсь": OBSERVE,
    "поговорить": TALK,
    "поговорить со стражником": TALK,
    "помочь": HELP_NEIGHBOUR,
    "помочь жительнице": HELP_NEIGHBOUR,
    "помочь собрать яблоки": HELP_NEIGHBOUR,
    "помощь": HELP,
}


def respond(action: str) -> str:
    """Recognise whole commands, never guess that an unknown action succeeded."""
    normalised = normalise_action(action)
    if not normalised:
        return "Введите действие. " + HELP
    return _REPLIES.get(
        normalised,
        "Я пока не понимаю это действие. Уточните его, пожалуйста. " + HELP,
    )
